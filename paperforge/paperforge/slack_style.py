"""Step 3: derive a matplotlib style from figures the lab posted in a Slack channel.

Only the look (fonts, colours, line widths) is taken from those images, never data.
Needs SLACK_BOT_TOKEN with scopes files:read and channels:read; without it the
built-in default style is used.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

import requests

from .llm import LLM, ask_json

DEFAULT_STYLE = {
    "font_family": "serif", "font_size": 9, "axes_linewidth": 0.8, "lines_linewidth": 1.5,
    "colors": ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd", "#8c564b"],
    "grid": False, "top_right_spines": False, "legend_frame": False,
}
API = "https://slack.com/api/"


def to_mplstyle(style: dict) -> str:
    s = {**DEFAULT_STYLE, **{k: v for k, v in style.items() if k in DEFAULT_STYLE and v is not None}}
    colors = [c.lstrip("#") for c in s["colors"] if re.fullmatch(r"#?[0-9a-fA-F]{6}", str(c))] or \
             [c.lstrip("#") for c in DEFAULT_STYLE["colors"]]
    family = s["font_family"] if s["font_family"] in {"serif", "sans-serif", "monospace"} else "serif"
    spines = "True" if s["top_right_spines"] else "False"
    return "\n".join([
        "# Generated by paperforge. Edit freely and re-run the scripts in figures/scripts/.",
        f"font.family: {family}",
        f"font.size: {float(s['font_size']):g}",
        f"axes.linewidth: {float(s['axes_linewidth']):g}",
        f"lines.linewidth: {float(s['lines_linewidth']):g}",
        f"axes.prop_cycle: cycler('color', {colors!r})",
        f"axes.grid: {'True' if s['grid'] else 'False'}",
        f"axes.spines.top: {spines}",
        f"axes.spines.right: {spines}",
        f"legend.frameon: {'True' if s['legend_frame'] else 'False'}",
        "figure.figsize: 3.4, 2.6",
        "savefig.bbox: tight",
        "savefig.dpi: 300",
        "pdf.fonttype: 42",
    ]) + "\n"


def _channel_id(session: requests.Session, channel: str) -> str:
    channel = channel.lstrip("#")
    if re.fullmatch(r"[CG][A-Z0-9]{8,}", channel):
        return channel
    cursor = ""
    while True:
        data = session.get(API + "conversations.list", params={"limit": 200, "cursor": cursor,
                           "exclude_archived": "true"}, timeout=30).json()
        if not data.get("ok"):
            raise RuntimeError(f"Slack conversations.list: {data.get('error')}")
        for ch in data["channels"]:
            if ch["name"] == channel:
                return ch["id"]
        cursor = data.get("response_metadata", {}).get("next_cursor", "")
        if not cursor:
            raise RuntimeError(f"Slack channel #{channel} not found (is the bot invited?)")


def download_images(channel: str, dest: Path, limit: int = 6) -> list[Path]:
    session = requests.Session()
    session.headers["Authorization"] = f"Bearer {os.environ['SLACK_BOT_TOKEN']}"
    data = session.get(API + "files.list", params={"channel": _channel_id(session, channel),
                       "types": "images", "count": limit}, timeout=30).json()
    if not data.get("ok"):
        raise RuntimeError(f"Slack files.list: {data.get('error')}")
    dest.mkdir(parents=True, exist_ok=True)
    out = []
    for i, f in enumerate(data.get("files", [])[:limit]):
        if f.get("filetype") not in {"png", "jpg", "jpeg"} or f.get("size", 0) > 4_000_000:
            continue
        resp = session.get(f["url_private_download"], timeout=60)
        resp.raise_for_status()
        path = dest / f"slack_{i}.{f['filetype']}"
        path.write_bytes(resp.content)
        out.append(path)
    return out


PROMPT = """These are figures from our lab's earlier papers. Describe only their visual style so new figures can match it. Ignore what the data shows.

Reply with JSON: {"font_family": "serif"|"sans-serif", "font_size": number (pt), "axes_linewidth": number, "lines_linewidth": number, "colors": ["#rrggbb", ...] (the main series colours, in order), "grid": bool, "top_right_spines": bool, "legend_frame": bool}"""


def build_style(llm: LLM, channel: str | None, workdir: Path) -> tuple[str, str]:
    """Return (mplstyle text, note for the report)."""
    if not channel:
        return to_mplstyle({}), "default style (no Slack channel given)"
    if not os.environ.get("SLACK_BOT_TOKEN"):
        return to_mplstyle({}), "default style (SLACK_BOT_TOKEN not set)"
    try:
        images = download_images(channel, workdir / "slack")
    except (requests.RequestException, RuntimeError, KeyError) as exc:
        return to_mplstyle({}), f"default style (Slack failed: {exc})"
    if not images:
        return to_mplstyle({}), f"default style (no png/jpg figures found in #{channel})"
    style = ask_json(llm, "style", PROMPT, images=images)
    return to_mplstyle(style if isinstance(style, dict) else {}), f"style taken from {len(images)} Slack figure(s) in #{channel.lstrip('#')}"
